import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const distDir = path.resolve('dist');
if (!fs.existsSync(distDir)) {
  console.error('dist/ không tồn tại. Hãy chạy `expo export -p web` trước.');
  process.exit(1);
}

const ALLOWED_EXTS = new Set(['.html', '.js', '.css', '.ttf', '.woff', '.woff2', '.png', '.ico', '.json', '.svg']);
const EXCLUDED_FILES = new Set(['/sw.js', '/metadata.json', '/assetmap.json', '/_expo/.routes.json']);
const EXCLUDED_PREFIXES = ['/_expo/static/js/android/', '/_expo/static/js/ios/'];

function walk(dir, results = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, results);
    } else {
      const relUrl = '/' + path.relative(distDir, full).split(path.sep).join('/');
      const ext = path.extname(entry.name).toLowerCase();
      if (!ALLOWED_EXTS.has(ext)) continue;
      if (entry.name.endsWith('.map')) continue;
      if (EXCLUDED_FILES.has(relUrl)) continue;
      if (EXCLUDED_PREFIXES.some((p) => relUrl.startsWith(p))) continue;
      results.push({ relUrl, full });
    }
  }
  return results;
}

const files = walk(distDir).sort((a, b) => a.relUrl.localeCompare(b.relUrl));
const hasher = crypto.createHash('sha256');
for (const f of files) {
  hasher.update(f.relUrl);
  hasher.update(fs.readFileSync(f.full));
}
const buildHash = hasher.digest('hex').slice(0, 12);
const precacheUrls = files.map((f) => f.relUrl);

const swSource = `// Auto-generated by scripts/generate-sw.mjs — do not edit manually
const CACHE_NAME = 'vc-pwa-${buildHash}';
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const PRECACHE_SET = new Set(PRECACHE_URLS);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/sw.js') return;

  if (req.mode === 'navigate') {
    let targetPath = url.pathname;
    if (targetPath === '/' || targetPath === '') {
      targetPath = '/index.html';
    } else if (!PRECACHE_SET.has(targetPath)) {
      const withHtml = targetPath.endsWith('/') ? targetPath.slice(0, -1) + '.html' : targetPath + '.html';
      targetPath = PRECACHE_SET.has(withHtml) ? withHtml : '/index.html';
    }

    event.respondWith(
      caches.open(CACHE_NAME).then((cache) =>
        cache.match(targetPath, { ignoreSearch: true }).then(
          (cached) => cached || fetch(req).catch(() => cache.match('/index.html'))
        )
      )
    );
    return;
  }

  event.respondWith(
    caches.open(CACHE_NAME).then((cache) =>
      cache.match(req, { ignoreSearch: true }).then((cached) => {
        if (cached) return cached;
        return fetch(req).then((resp) => {
          if (resp && resp.status === 200 && resp.type === 'basic') {
            cache.put(req, resp.clone());
          }
          return resp;
        });
      })
    )
  );
});
`;

fs.writeFileSync(path.join(distDir, 'sw.js'), swSource, 'utf8');
console.log(`Generated dist/sw.js (${precacheUrls.length} files, cache vc-pwa-${buildHash})`);
